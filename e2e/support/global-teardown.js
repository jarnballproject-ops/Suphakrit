import { configured, reap, E2E_PREFIX } from './db.js'

/**
 * กวาดข้อมูลของเทสต์ที่ค้างในฐานข้อมูลจริง
 * ----------------------------------------------------------------------------
 * ทุกเทสต์เก็บกวาดของตัวเองอยู่แล้ว แต่เทสต์ที่ล้มกลางทางไม่ได้เก็บ
 * ชุดนี้ยิงเข้าฐานข้อมูลของร้านจริง ของค้างจึงกลายเป็นเมนู/โต๊ะปลอมที่พนักงานเห็น
 *
 * ตัวที่ลบไม่ออกจะถูกพิมพ์ออกมา (เมนูที่เคยถูกสั่งติด FK ลบไม่ได้ ต้องปิดใช้งานแทน)
 * ก่อนส่งมอบให้ดูบรรทัดนี้ — ต้องไม่มีอะไรค้าง
 */
export default async function globalTeardown() {
  if (!configured) return
  const stuck = await reap().catch((e) => [`reap ล้มเหลว: ${e.message}`])
  if (stuck.length) {
    console.log(`\n⚠️  ข้อมูลเทสต์ที่ลบไม่ออก (${stuck.length}) — ต้องเก็บด้วยมือก่อนส่งมอบ:`)
    for (const s of stuck) console.log(`   ${s}`)
  } else {
    console.log(`\n🧹 ไม่มีข้อมูล ${E2E_PREFIX}* ค้างในฐานข้อมูล`)
  }
}
